def review_auxiliary(kind, clause, *, section, block, value, declared):
    token = section.get('section_token')
    expected = SECTION_TEXT_SHA256.get(token)
    if not expected or sha256(section.get('text', '').encode()).hexdigest() != expected:
        return None
    context = {k: section.get(k) for k in ['text', 'tables', 'page_layouts', 'pages', 'outline', 'first_page']}
    if sha256(json.dumps(context, sort_keys=True, ensure_ascii=False).encode()).hexdigest() != SECTION_CONTEXT_SHA256.get(token):
        return None
    key = (token, kind, block.get('page'), sha256(clause.encode()).hexdigest())
    expected_block = SOURCE_BLOCK_GUARDS.get(key)
    if expected_block is None or any(block.get(k) != v for k, v in expected_block.items()):
        return None
    reviewed = REVIEWED_RELATIONS.get(key)
    if reviewed is None:
        return None
    subjects = reviewed['value_updates']['subjects']
    names = {str(name).casefold() for name in declared}
    if any(subject['operand'].casefold() not in names for subject in subjects):
        return None
    # Error causes must still be bound to a literal cause column by the parser.
    if kind == 'error' and block.get('has_action_column') and not block.get('cause_cell_bound'):
        return None
    return deepcopy(reviewed)

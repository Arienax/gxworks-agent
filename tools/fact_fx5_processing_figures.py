def _operands(value):
    if isinstance(value, dict):
        if 'operand' in value:
            yield value['operand']
        for child in value.values():
            yield from _operands(child)
    elif isinstance(value, list):
        for child in value:
            yield from _operands(child)


def review_processing_clause(clause, *, section, block, value, declared):
    selected = REVIEWED_FIGURES.get((block['page'], clause))
    if selected is None:
        return None
    result = deepcopy(selected)
    subjects = sorted(set(_operands(result['rules'])))
    if not set(subjects).issubset({str(item).casefold() for item in declared}):
        return None
    result['full_clause_review'] = True
    result['value_updates'] = {
        'subjects': [{'operand': name} for name in subjects],
        'operand_binding_required': bool(subjects), 'numeric_values': [], 'ranges': [], 'comparisons': [],
        'source_formulas': [], 'unresolved_glyphs': [], 'unparsed_input_qualification': False,
        'unbound_condition_markers': [], 'context_binding': 'resolved',
        'knowledge_kind': 'manual_behavior', 'notation_review_basis': 'original_PDF_visual_review',
        **result.get('value_updates', {})}
    return result

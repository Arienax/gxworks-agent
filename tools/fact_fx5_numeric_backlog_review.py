def review_numeric_backlog_clause(kind, clause, *, section, block, value, declared):
    """Return a complete authored relation only for its exact verified context.

    This does not weaken the caller's error, model, language, instruction-form,
    or operand checks. The caller must continue its normal fact validation.
    """
    if not isinstance(clause, str) or not isinstance(block.get('text'), str):
        return None
    entry = _INDEX.get((kind, block.get('page'), _digest(clause)))
    if entry is None:
        return None
    if (section.get('first_page') != entry['first_page'] or
            _digest(block['text']) != entry['block_sha256'] or
            _structure_digest(block) != entry['block_structure_sha256'] or
            _artifact_digest(section) != entry['section_artifacts_sha256'] or
            _digest(section.get('outline', '')) != entry['outline_sha256'] or
            _digest(section.get('text', '')) != entry['section_sha256'] or
            not set(entry['required_operands']).issubset(declared)):
        return None
    return deepcopy(entry['review'])

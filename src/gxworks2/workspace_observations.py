"""Strict vendor observations and stable evidence origins for current adapters.

The C# collector owns live interfaces and version selection. ABI checks expose
semantic evidence to GXW Core; no vendor call parameters are accepted here.
Historical receipts require the separate explicit offline compatibility decoder.
"""
from __future__ import annotations

from enum import Enum

from gxw.models import GXWFormatError


class EvidenceOrigin(str, Enum):
    """Stable collector origins; descriptions are never evidence identifiers."""

    CODE_LEXICAL_READ = 'code_lexical_read'
    OWNED_CHECK_INPUT = 'owned_check_input'
    SOURCE_BODY = 'source_body'
    SOURCE_REFERENCES = 'source_references'
    TASK_SELECTION = 'task_selection'
    SFC_LENGTH_PREFIX = 'sfc_length_prefix'
    STRUCTURED_CHECK_ENVELOPE = 'structured_check_envelope'


def evidence_origin_bound(row, origin):
    """Accept only the versioned, typed origin assigned by the collector."""
    evidence = row.get('evidence') if isinstance(row, dict) else None
    return (isinstance(evidence, dict) and evidence.keys() == {'schema_version', 'origin'}
            and type(evidence['schema_version']) is int and evidence['schema_version'] == 1
            and type(evidence['origin']) is str and evidence['origin'] == origin.value)


def native_code_reader_scope(cpu):
    """Observed converter contexts, bound to exact CPU menu selections."""
    if cpu == 'Q03UDV':
        return {'scope_cpu': cpu, 'profile': 'q03udv', 'module': 'ECCodeGenerator2.dll',
                'version': '15.41', 'native_cpu': 209, 'native_versions': [25]}
    if cpu == 'FX3U/FX3UC':
        return {'scope_cpu': cpu, 'profile': 'fx3u', 'module': 'ECCodeGeneratorFX2.dll',
                'version': '15.31', 'native_cpu': 520, 'native_versions': []}
    if cpu == 'FXU/FX2C':
        # Original UI project Param.wpa, then original 15.31 Open/decode/prefix
        # reads of this CPU's generated bytes; the grammar is not a CPU alias.
        return {'scope_cpu': cpu, 'profile': 'fx', 'module': 'ECCodeGeneratorFX2.dll',
                'version': '15.31', 'native_cpu': 516, 'native_versions': []}
    if cpu == 'FX3G':
        # Original FX3G/FX3GC menu project stores FX3G/521. Its own generated
        # bytes agree with original 15.31 lexical and prefix-step reads.
        return {'scope_cpu': cpu, 'profile': 'fx3g', 'module': 'ECCodeGeneratorFX2.dll',
                'version': '15.31', 'native_cpu': 521, 'native_versions': []}
    return None


def check_input_kind(event, *, native_version, checker_version):
    backend = event.get('input_backend')
    sfc = isinstance(backend, dict) and backend.get('module') == 'DZDataABS_Compiler.dll'
    if native_version != '1.635.0.1' or checker_version != ('1.635.0.1' if sfc else '15.50'):
        return None
    return 'sfc' if sfc else 'structured'


def check_input_layout_bound(event, *, sfc):
    if (event.get('compiler_member_offset') != (8 if sfc else 12)
            or event.get('manager_records_offset') != 32):
        return False
    if sfc and event.get('input_backend') != {'module': 'DZDataABS_Compiler.dll', 'version': '1.635.0.1',
                                             'progress_rva': 0x73e5, 'program_check_rva': 0x4810}:
        return False
    contract = event.get('input_contract')
    return contract is None or contract == {'schema_version': 1, 'kind': 'sfc' if sfc else 'structured', 'status': 'verified'}


def check_input_framing_bound(framing, *, sfc):
    return (framing.get('reader_module') == 'DZDataABS_SICConverter.dll'
        and framing.get('reader_version') == '1.635.0.1'
        and evidence_origin_bound(framing, EvidenceOrigin.SFC_LENGTH_PREFIX)) if sfc else (
        framing.get('reader_module') == 'ECCompiler_IEC.dll' and framing.get('reader_version') == '15.50'
        and framing.get('reader_rva') == 0x39f30 and framing.get('code') == 0
        and evidence_origin_bound(framing, EvidenceOrigin.STRUCTURED_CHECK_ENVELOPE))


def workspace_read_scope_verified(events):
    modules = {}
    for event in events:
        if event.get('operation') == 'OwnedBackendModule':
            modules.setdefault(str(event.get('name', '')).lower(), set()).add(event.get('version'))
    return all(modules.get(name) == {'1.635.0.1'} for name in (
        'dzdataabs_workspace.dll', 'dzdataabs_compileradapter.dll', 'dzdataabs_compiler_iec.dll'))


def workspace_code_read_origin(row, *, scope_verified, publication_target):
    verified = scope_verified
    caller, stack = row.get('caller') or {}, row.get('stack') or []
    stack_modules = {str(frame.get('module', '')).lower() for frame in stack if frame.get('module')}
    native = (verified and str(caller.get('module', '')).lower() == 'dzdataabs_converter.dll'
        and caller.get('rva') in ('0x829a2', '0x82a34')
        and any(str(frame.get('module', '')).lower() == 'dzdataabs_compileradapter.dll'
            and frame.get('rva') in ('0x6c0e', '0x6c82') for frame in stack))
    publication = (verified and not caller.get('module') and bool(caller.get('address'))
        and stack_modules == {'dzdataabs_workspace.dll', 'clr.dll'} and publication_target)
    return 'native-checker' if native else 'auxiliary-publication' if publication else 'unknown'


def task_configuration_values(configuration):
    values = {}
    for field, offset in (('event_name', 1584), ('interval', 1592), ('priority', 1600)):
        getter = configuration[field]
        if (type(getter.get('interface_byte_offset')) is not int or getter['interface_byte_offset'] != offset
                or type(getter.get('hresult')) is not int or getter['hresult'] < 0
                or type(getter.get('code')) is not int or getter['code'] != 0
                or getter.get('field', field) != field):
            raise GXWFormatError('native task configuration getter is not bound to the observed interface')
        values[field] = getter['value']
    return values


def source_reference_modules_bound(events):
    return all({row.get('version') for row in events if row.get('operation') == 'OwnedBackendModule'
                and row.get('name') == name} == {'1.635.0.1'}
               for name in ('DZDataABS_CompilerAdapter.dll', 'DZDataABS_Compiler_IEC.dll'))


def structured_input_reader_bound(item):
    return (isinstance(item, dict) and item.get('framing', {}).get('reader_module') == 'ECCompiler_IEC.dll'
            and item['framing'].get('reader_version') == '15.50')


def public_report_converter_bound(row):
    return (row.get('module') == 'DZDataABS_CompilerAdapter.dll' and row.get('version') == '1.635.0.1'
            and row.get('converter_rva') == 0x8e48 and row.get('original_record_size') == 68
            and row.get('record_size') == 100)


def source_named_check_diagnostics(row, *, resource=None, reports=()):
    backend = row.get('input_backend')
    if (isinstance(backend, dict) and backend.get('module') == 'DZDataABS_Compiler.dll'
            and backend.get('version') == '1.635.0.1'):
        return True
    rows = row.get('rows')
    return (row.get('input_contract') == {'schema_version': 1, 'kind': 'structured', 'status': 'verified'}
        and check_input_layout_bound(row, sfc=False)
        and isinstance(rows, list) and bool(rows) and all(structured_input_reader_bound(item) for item in rows)
        and any(report.get('kind') in (2, 3) and report.get('name', {}).get('text') != resource for report in reports))


def check_input_versions(events, first_copy):
    versions = {(row.get('name'), row.get('version')) for row in events if row.get('operation') == 'OwnedBackendModule'}
    ec_version = '15.50' if {version for name, version in versions if name == 'ECCompiler_IEC.dll'} == {'15.50'} else None
    backend = first_copy.get('input_backend')
    sfc = isinstance(backend, dict) and backend.get('module') == 'DZDataABS_Compiler.dll'
    required = {'DZDataABS_CompilerAdapter.dll', 'DZDataABS_Compiler.dll', 'DZDataABS_SICConverter.dll'} if sfc else {
        'DZDataABS_CompilerAdapter.dll', 'DZDataABS_Compiler_IEC.dll', 'DZDataABS_SICConverter_IEC.dll'}
    owner_version = '1.635.0.1' if all((name, '1.635.0.1') in versions
        and all(version == '1.635.0.1' for module, version in versions if module == name) for name in required) else None
    return owner_version, owner_version if sfc else ec_version
